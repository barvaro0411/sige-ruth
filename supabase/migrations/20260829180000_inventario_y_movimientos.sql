-- =============================================================================
-- Fase 2 — Inventario: categorías, productos y movimientos
--
-- Principio: `inventario_movimientos` es la única fuente de verdad del stock.
-- `inventario_items.stock_actual` es una caché mantenida por trigger, para que
-- «productos bajo stock mínimo» sea una consulta barata y no una suma de todo
-- el historial. Si alguna vez queda descuadrada, `recalcular_stock()` la
-- reconstruye desde cero.
--
-- Un movimiento no se edita ni se borra: un error se corrige con un movimiento
-- de ajuste. Es la única forma de que el historial explique el stock.
--
-- Desvío respecto de la especificación: el estado «agotado» no se guarda, se
-- deriva. Un estado almacenado termina discrepando de los movimientos, y
-- entonces hay dos verdades. Se guarda solo `activo` (para dar de baja un
-- producto) y el resto sale de la vista `inventario_estado_vista`.
-- =============================================================================

begin;

-- -----------------------------------------------------------------------------
-- 1. Catálogos configurables
--
-- Ni las unidades ni las categorías se escriben en el código: cambian con el
-- tiempo y las administra la escuela.
-- -----------------------------------------------------------------------------
create table if not exists public.inventario_unidades (
  codigo     text primary key,
  nombre     text not null,
  activo     boolean not null default true,
  created_at timestamptz not null default now()
);

insert into public.inventario_unidades (codigo, nombre) values
  ('unidad',   'Unidad'),
  ('paquete',  'Paquete'),
  ('caja',     'Caja'),
  ('rollo',    'Rollo'),
  ('litro',    'Litro'),
  ('kilo',     'Kilo'),
  ('resma',    'Resma'),
  ('bolsa',    'Bolsa'),
  ('pliego',   'Pliego'),
  ('set',      'Set')
on conflict (codigo) do nothing;

create table if not exists public.inventario_categorias (
  id         bigint generated by default as identity primary key,
  nombre     text not null check (length(btrim(nombre)) between 2 and 80),
  activo     boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- Las categorías son de la escuela, no de una sede: «Cartulina» es lo mismo
-- en Gambino que en Vascongados. Lo que es por sede es el stock.
create unique index if not exists inventario_categorias_nombre_uidx
  on public.inventario_categorias (lower(btrim(nombre)));

insert into public.inventario_categorias (nombre)
select v.nombre from (values
  ('Papelería y cartulinas'),
  ('Material pedagógico'),
  ('Material fonoaudiológico'),
  ('Útiles y escritura'),
  ('Pegamentos y adhesivos'),
  ('Pinturas y témperas'),
  ('Artículos de oficina'),
  ('Insumos de aseo'),
  ('Higiene y baño'),
  ('Cocina y colación'),
  ('Otros')
) as v(nombre)
where not exists (
  select 1 from public.inventario_categorias c
  where lower(btrim(c.nombre)) = lower(btrim(v.nombre))
);

-- -----------------------------------------------------------------------------
-- 2. Productos
--
-- El stock es físico: un producto pertenece a una sede. El mismo nombre puede
-- existir en ambas y llevar su propia cuenta.
-- -----------------------------------------------------------------------------
create table if not exists public.inventario_items (
  id            bigint generated by default as identity primary key,
  sede_id       text   not null references public.sedes(id) on update cascade on delete restrict,
  categoria_id  bigint not null references public.inventario_categorias(id) on update cascade on delete restrict,
  nombre        text   not null check (length(btrim(nombre)) between 2 and 120),
  descripcion   text,
  unidad        text   not null default 'unidad'
                  references public.inventario_unidades(codigo) on update cascade on delete restrict,

  -- Caché derivada de los movimientos. Nunca se escribe a mano: un trigger la
  -- mantiene y otro rechaza el UPDATE directo.
  stock_actual  numeric(12,2) not null default 0 check (stock_actual >= 0),
  stock_minimo  numeric(12,2) not null default 0 check (stock_minimo >= 0),

  ubicacion     text,
  activo        boolean not null default true,
  archived_at   timestamptz,
  created_by    uuid references public.perfiles(id) on update cascade on delete set null default auth.uid(),
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now()
);

-- Sin productos duplicados en la misma sede: dos «Cartulina roja» significan
-- dos stocks que nadie sabe cuál mirar.
create unique index if not exists inventario_items_sede_nombre_uidx
  on public.inventario_items (sede_id, lower(btrim(nombre)));

create index if not exists inventario_items_sede_categoria_idx
  on public.inventario_items (sede_id, categoria_id) where activo;

-- Para la pantalla de «productos bajo stock mínimo», que es la que se mira.
create index if not exists inventario_items_bajo_stock_idx
  on public.inventario_items (sede_id)
  where activo and stock_actual <= stock_minimo;

-- -----------------------------------------------------------------------------
-- 3. Movimientos — la fuente de verdad
--
-- `cantidad` va con signo. La dirección la impone el tipo: una compra nunca
-- resta y una entrega nunca suma. El ajuste es el único que puede ir a ambos
-- lados, y por eso es el que se usa para corregir.
-- -----------------------------------------------------------------------------
create table if not exists public.inventario_movimientos (
  id            bigint generated by default as identity primary key,
  item_id       bigint not null references public.inventario_items(id) on update cascade on delete restrict,
  sede_id       text   not null references public.sedes(id) on update cascade on delete restrict,
  tipo          text   not null check (tipo in ('ingreso','compra','devolucion','entrega','baja','ajuste')),
  cantidad      numeric(12,2) not null check (cantidad <> 0),
  motivo        text,
  observaciones text,
  solicitud_id  bigint references public.solicitudes_materiales(id) on update cascade on delete set null,
  actor_id      uuid references public.perfiles(id) on update cascade on delete set null default auth.uid(),
  created_at    timestamptz not null default now(),

  constraint movimiento_signo_coherente check (
    (tipo in ('ingreso','compra','devolucion') and cantidad > 0)
    or (tipo in ('entrega','baja') and cantidad < 0)
    or tipo = 'ajuste'
  )
);

create index if not exists inventario_movimientos_item_idx
  on public.inventario_movimientos (item_id, created_at desc);
create index if not exists inventario_movimientos_sede_fecha_idx
  on public.inventario_movimientos (sede_id, created_at desc);
create index if not exists inventario_movimientos_solicitud_idx
  on public.inventario_movimientos (solicitud_id) where solicitud_id is not null;

comment on table public.inventario_movimientos is
  'Historial de stock. Append-only: no se edita ni se borra. Un error se corrige con un movimiento de ajuste.';

-- -----------------------------------------------------------------------------
-- 4. Aplicar el movimiento al stock
--
-- Bloquea la fila del producto antes de leer el stock. Sin ese `for update`,
-- dos entregas simultáneas leen el mismo saldo, las dos pasan la validación y
-- el inventario queda en negativo.
-- -----------------------------------------------------------------------------
create or replace function public.aplicar_movimiento_inventario()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  it public.inventario_items;
  resultante numeric(12,2);
begin
  select * into it from public.inventario_items where id = new.item_id for update;
  if not found then
    raise exception 'El producto no existe';
  end if;

  if not it.activo then
    raise exception 'El producto "%" está dado de baja: reactívalo antes de moverlo', it.nombre;
  end if;

  -- La sede del movimiento la manda el producto, no el cliente.
  new.sede_id := it.sede_id;

  resultante := it.stock_actual + new.cantidad;
  if resultante < 0 then
    raise exception 'Stock insuficiente de "%": hay % % y se intentan sacar %',
      it.nombre, it.stock_actual, it.unidad, abs(new.cantidad);
  end if;

  -- Marca la sesión para que proteger_stock_actual() deje pasar este UPDATE:
  -- es el único camino legítimo por el que cambia el stock.
  perform set_config('app.movimiento_inventario', 'ok', true);
  update public.inventario_items
  set stock_actual = resultante, updated_at = now()
  where id = new.item_id;
  perform set_config('app.movimiento_inventario', '', true);

  return new;
end;
$$;

drop trigger if exists inventario_movimientos_aplicar on public.inventario_movimientos;
create trigger inventario_movimientos_aplicar
  before insert on public.inventario_movimientos
  for each row execute function public.aplicar_movimiento_inventario();

-- Un movimiento es un hecho: no se reescribe la historia.
create or replace function public.movimientos_son_inmutables()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  raise exception 'Un movimiento de inventario no se modifica ni se elimina. Registra un ajuste para corregir.';
end;
$$;

drop trigger if exists inventario_movimientos_inmutables on public.inventario_movimientos;
create trigger inventario_movimientos_inmutables
  before update or delete on public.inventario_movimientos
  for each row execute function public.movimientos_son_inmutables();

-- -----------------------------------------------------------------------------
-- 5. El stock no se escribe a mano
--
-- Sin esto, cualquiera con permiso de editar el producto podría corregir el
-- número y dejar el historial diciendo otra cosa.
-- -----------------------------------------------------------------------------
create or replace function public.proteger_stock_actual()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  if new.stock_actual is distinct from old.stock_actual
     and coalesce(current_setting('app.movimiento_inventario', true), '') <> 'ok' then
    raise exception 'El stock se cambia registrando un movimiento, no editando el producto';
  end if;
  return new;
end;
$$;

drop trigger if exists inventario_items_proteger_stock on public.inventario_items;
create trigger inventario_items_proteger_stock
  before update on public.inventario_items
  for each row execute function public.proteger_stock_actual();

drop trigger if exists inventario_items_set_updated_at on public.inventario_items;
create trigger inventario_items_set_updated_at
  before update on public.inventario_items
  for each row execute function public.set_updated_at();

drop trigger if exists inventario_categorias_set_updated_at on public.inventario_categorias;
create trigger inventario_categorias_set_updated_at
  before update on public.inventario_categorias
  for each row execute function public.set_updated_at();

drop trigger if exists inventario_items_audit on public.inventario_items;
create trigger inventario_items_audit
  after insert or update or delete on public.inventario_items
  for each row execute function public.audit_row_change();

-- -----------------------------------------------------------------------------
-- 6. Reconstruir el stock desde el historial
--
-- La red de seguridad de tener una caché. Si el número quedó descuadrado por
-- lo que sea, esto lo recalcula sumando los movimientos.
-- -----------------------------------------------------------------------------
create or replace function public.recalcular_stock(p_item_id bigint default null)
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  corregidos integer := 0;
begin
  if not public.gestiona_bodega() then
    raise exception 'No tienes autorización para recalcular el stock';
  end if;

  perform set_config('app.movimiento_inventario', 'ok', true);

  with real as (
    select i.id, coalesce(sum(m.cantidad), 0)::numeric(12,2) as stock
    from public.inventario_items i
    left join public.inventario_movimientos m on m.item_id = i.id
    where (p_item_id is null or i.id = p_item_id)
      and public.can_access_sede(i.sede_id)
    group by i.id
  )
  update public.inventario_items i
  set stock_actual = real.stock, updated_at = now()
  from real
  where i.id = real.id and i.stock_actual is distinct from real.stock;

  get diagnostics corregidos = row_count;
  perform set_config('app.movimiento_inventario', '', true);
  return corregidos;
end;
$$;

comment on function public.recalcular_stock(bigint) is
  'Reconstruye stock_actual sumando los movimientos. Devuelve cuántos productos estaban descuadrados.';

-- -----------------------------------------------------------------------------
-- 7. Estado derivado
--
-- «Agotado» y «bajo mínimo» se calculan, no se guardan: un estado almacenado
-- termina discrepando de los movimientos y entonces hay dos verdades.
-- -----------------------------------------------------------------------------
create or replace view public.inventario_estado_vista
with (security_invoker = true) as
select
  i.id,
  i.sede_id,
  i.categoria_id,
  c.nombre        as categoria,
  i.nombre,
  i.descripcion,
  i.unidad,
  u.nombre        as unidad_nombre,
  i.stock_actual,
  i.stock_minimo,
  i.ubicacion,
  i.activo,
  case
    when i.stock_actual <= 0                              then 'agotado'
    when i.stock_minimo > 0 and i.stock_actual <= i.stock_minimo then 'bajo'
    else 'ok'
  end as estado_stock,
  greatest(i.stock_minimo - i.stock_actual, 0)::numeric(12,2) as faltante,
  i.created_at,
  i.updated_at
from public.inventario_items i
join public.inventario_categorias c on c.id = i.categoria_id
join public.inventario_unidades   u on u.codigo = i.unidad;

comment on view public.inventario_estado_vista is
  'Productos con su estado de stock derivado. security_invoker: cada quien ve las sedes que la RLS le permite.';

-- -----------------------------------------------------------------------------
-- 8. RLS
--
-- Ver el inventario lo puede hacer todo el personal activo de la sede: saber si
-- queda cartulina no es información sensible y evita preguntar por WhatsApp.
-- Moverlo y administrarlo, solo quien gestiona bodega.
-- -----------------------------------------------------------------------------
alter table public.inventario_unidades    enable row level security;
alter table public.inventario_categorias  enable row level security;
alter table public.inventario_items       enable row level security;
alter table public.inventario_movimientos enable row level security;

drop policy if exists "unidades_select" on public.inventario_unidades;
create policy "unidades_select" on public.inventario_unidades
  for select to authenticated using (public.is_active_user());
drop policy if exists "unidades_manage" on public.inventario_unidades;
create policy "unidades_manage" on public.inventario_unidades
  for all to authenticated
  using (public.has_role(array['director','sostenedor']))
  with check (public.has_role(array['director','sostenedor']));

drop policy if exists "categorias_select" on public.inventario_categorias;
create policy "categorias_select" on public.inventario_categorias
  for select to authenticated using (public.is_active_user());
drop policy if exists "categorias_manage" on public.inventario_categorias;
create policy "categorias_manage" on public.inventario_categorias
  for all to authenticated
  using (public.gestiona_bodega())
  with check (public.gestiona_bodega());

drop policy if exists "items_select_sede" on public.inventario_items;
create policy "items_select_sede" on public.inventario_items
  for select to authenticated using (public.can_access_sede(sede_id));

drop policy if exists "items_manage_bodega" on public.inventario_items;
create policy "items_manage_bodega" on public.inventario_items
  for all to authenticated
  using (public.can_access_sede(sede_id) and public.gestiona_bodega())
  with check (public.can_access_sede(sede_id) and public.gestiona_bodega());

drop policy if exists "movimientos_select_sede" on public.inventario_movimientos;
create policy "movimientos_select_sede" on public.inventario_movimientos
  for select to authenticated using (public.can_access_sede(sede_id));

-- Solo INSERT: el historial no se edita ni se borra, y los triggers de arriba
-- lo impiden aunque alguien cambie esta política.
drop policy if exists "movimientos_insert_bodega" on public.inventario_movimientos;
create policy "movimientos_insert_bodega" on public.inventario_movimientos
  for insert to authenticated
  with check (
    public.gestiona_bodega()
    and exists (
      select 1 from public.inventario_items i
      where i.id = item_id and public.can_access_sede(i.sede_id)
    )
  );

