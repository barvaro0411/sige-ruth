grant select on public.inventario_categorias  to authenticated;
grant select on public.inventario_items       to authenticated;
grant select on public.inventario_movimientos to authenticated;
grant select on public.inventario_estado_vista to authenticated;

grant insert, update, delete on public.inventario_unidades   to authenticated;
grant insert, update, delete on public.inventario_categorias to authenticated;
grant insert, update, delete on public.inventario_items      to authenticated;
grant insert                 on public.inventario_movimientos to authenticated;
grant usage, select on all sequences in schema public to authenticated;

revoke all on public.inventario_unidades     from anon;
revoke all on public.inventario_categorias   from anon;
revoke all on public.inventario_items        from anon;
revoke all on public.inventario_movimientos  from anon;
revoke all on public.inventario_estado_vista from anon;

revoke all on function public.aplicar_movimiento_inventario() from public, anon, authenticated;
