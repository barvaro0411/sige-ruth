-- =============================================================================
-- Fase 6 — Mantenciones preventivas
--
-- Lo que se repite y se olvida: extintores, calefactores, canaletas antes de
-- las lluvias. No es una lista de tareas: es una lista de cosas con una
-- frecuencia, y la base calcula sola cuando toca la proxima.
--
-- `proxima_fecha` es una columna generada — ultima ejecucion (o el inicio, si
-- nunca se hizo) mas la frecuencia. Nadie la escribe a mano, asi que no puede
-- quedar desfasada del historial de ejecuciones.
--
-- Reconstruida desde el estado real de produccion (version 20260829182149).
-- =============================================================================

begin;

create table if not exists public.mantenciones_preventivas (
  id              bigint generated by default as identity primary key,
  sede_id         text not null references public.sedes(id) on update cascade on delete restrict,
  categoria_id    bigint not null references public.mantencion_categorias(id) on update cascade on delete restrict,
  nombre          text not null check (length(btrim(nombre)) between 3 and 120),
  ubicacion       text,
  observaciones   text,
  frecuencia_dias smallint not null check (frecuencia_dias between 1 and 3650),
  fecha_inicio    date not null default current_date,
  ultima_fecha    date,
  proxima_fecha   date generated always as
                    (coalesce(ultima_fecha, fecha_inicio) + frecuencia_dias::integer) stored,
  responsable_id  uuid references public.perfiles(id) on update cascade on delete set null,
  activo          boolean not null default true,
  created_at      timestamptz not null default now(),
  updated_at      timestamptz not null default now(),

  -- La ultima ejecucion no puede estar en el futuro. El +1 dia deja pasar el
  -- desfase de zona horaria sin tener que pelear con el.
  constraint ultima_no_futura check (ultima_fecha is null or ultima_fecha <= current_date + 1)
);

comment on table public.mantenciones_preventivas is
  'Lo que se repite: extintores, calefactores, canaletas. proxima_fecha se calcula sola desde la ultima vez mas la frecuencia.';

create index if not exists preventivas_sede_proxima_idx
  on public.mantenciones_preventivas (sede_id, proxima_fecha) where activo;

-- -----------------------------------------------------------------------------
-- Ejecuciones: cada vez que se hizo, con su costo
-- -----------------------------------------------------------------------------
create table if not exists public.preventivas_ejecuciones (
  id            bigint generated by default as identity primary key,
  preventiva_id bigint not null references public.mantenciones_preventivas(id) on delete cascade,
  fecha         date not null default current_date,
  realizada_por uuid default auth.uid()
                  references public.perfiles(id) on update cascade on delete set null,
  proveedor     text,
  costo         numeric(12,2) check (costo >= 0),
  observaciones text,
  created_at    timestamptz not null default now(),

  constraint ejecucion_no_futura check (fecha <= current_date + 1)
);

create index if not exists preventivas_ejecuciones_idx
  on public.preventivas_ejecuciones (preventiva_id, fecha desc);

-- `ultima_fecha` se deriva del maximo de las ejecuciones, no del ultimo insert:
-- asi cargar una ejecucion vieja con retraso no adelanta la proxima.
create or replace function public.actualizar_ultima_preventiva()
returns trigger
language plpgsql
security definer
set search_path = public
as $fn$
begin
  update public.mantenciones_preventivas p
  set ultima_fecha = (
        select max(e.fecha) from public.preventivas_ejecuciones e
        where e.preventiva_id = p.id
      ),
      updated_at = now()
  where p.id = coalesce(new.preventiva_id, old.preventiva_id);
  return null;
end;
$fn$;

drop trigger if exists preventivas_set_updated_at on public.mantenciones_preventivas;
create trigger preventivas_set_updated_at
  before update on public.mantenciones_preventivas
  for each row execute function public.set_updated_at();

drop trigger if exists preventivas_audit on public.mantenciones_preventivas;
create trigger preventivas_audit
  after insert or delete or update on public.mantenciones_preventivas
  for each row execute function public.audit_row_change();

drop trigger if exists preventivas_ejecuciones_actualizar on public.preventivas_ejecuciones;
create trigger preventivas_ejecuciones_actualizar
  after insert or delete or update on public.preventivas_ejecuciones
  for each row execute function public.actualizar_ultima_preventiva();

-- -----------------------------------------------------------------------------
-- Vista: vencidas primero, proximas despues
-- -----------------------------------------------------------------------------
create or replace view public.preventivas_estado_vista
with (security_invoker = true) as
select
  p.id, p.sede_id, p.categoria_id, c.nombre as categoria,
  p.nombre, p.ubicacion, p.observaciones,
  p.frecuencia_dias, p.fecha_inicio, p.ultima_fecha, p.proxima_fecha,
  p.responsable_id, r.nombre as responsable_nombre, p.activo,
  p.proxima_fecha - public.hoy_santiago() as dias_restantes,
  case
    when p.proxima_fecha < public.hoy_santiago()      then 'vencida'
    when p.proxima_fecha <= public.hoy_santiago() + 30 then 'proxima'
    else 'al_dia'
  end as estado_preventiva
from public.mantenciones_preventivas p
join public.mantencion_categorias c on c.id = p.categoria_id
left join public.perfiles r on r.id = p.responsable_id;

-- -----------------------------------------------------------------------------
-- RLS — todos ven lo que viene; solo mantencion lo configura y lo marca hecho
-- -----------------------------------------------------------------------------
alter table public.mantenciones_preventivas enable row level security;
alter table public.preventivas_ejecuciones  enable row level security;

drop policy if exists "preventivas_select" on public.mantenciones_preventivas;
create policy "preventivas_select" on public.mantenciones_preventivas
  for select to authenticated
  using (public.can_access_sede(sede_id));

drop policy if exists "preventivas_manage" on public.mantenciones_preventivas;
create policy "preventivas_manage" on public.mantenciones_preventivas
  for all to authenticated
  using (public.can_access_sede(sede_id) and public.gestiona_mantencion())
  with check (public.can_access_sede(sede_id) and public.gestiona_mantencion());

drop policy if exists "preventivas_ejec_select" on public.preventivas_ejecuciones;
create policy "preventivas_ejec_select" on public.preventivas_ejecuciones
  for select to authenticated
  using (exists (
    select 1 from public.mantenciones_preventivas p
    where p.id = preventiva_id and public.can_access_sede(p.sede_id)
  ));

-- Una ejecucion registrada no se edita ni se borra: es historia. Si se cargo
-- mal, se registra la correcta y la observacion lo explica.
drop policy if exists "preventivas_ejec_insert" on public.preventivas_ejecuciones;
create policy "preventivas_ejec_insert" on public.preventivas_ejecuciones
  for insert to authenticated
  with check (public.gestiona_mantencion() and exists (
    select 1 from public.mantenciones_preventivas p
    where p.id = preventiva_id and public.can_access_sede(p.sede_id)
  ));

grant select, insert, update, delete on public.mantenciones_preventivas to authenticated;
grant select, insert                 on public.preventivas_ejecuciones  to authenticated;
grant select                         on public.preventivas_estado_vista to authenticated;

revoke all on public.mantenciones_preventivas from anon;
revoke all on public.preventivas_ejecuciones  from anon;
revoke all on public.preventivas_estado_vista from anon;
revoke truncate, trigger, references on public.mantenciones_preventivas,
  public.preventivas_ejecuciones from anon, authenticated;

revoke all on function public.actualizar_ultima_preventiva() from public, anon, authenticated;

commit;
