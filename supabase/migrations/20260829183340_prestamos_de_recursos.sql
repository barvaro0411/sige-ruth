-- =============================================================================
-- Fase 7 — Prestamos de recursos
--
-- Equipos que se prestan y vuelven: notebooks, proyectores, parlantes. El
-- problema real no es prestar, es acordarse de quien lo tiene.
--
-- Dos decisiones que sostienen el modulo:
--   · Un indice unico parcial garantiza un solo prestamo activo por recurso.
--     No hay forma de prestar dos veces lo mismo, ni con dos personas
--     registrando a la vez.
--   · `recursos.estado` se sincroniza solo desde los prestamos, pero solo entre
--     `disponible` y `prestado`. Si alguien marco un equipo en `mantencion` o
--     `no_disponible`, eso lo puso una persona a proposito y no se pisa.
--
-- `codigo` esta pensado para un QR pegado al equipo, para cuando se quiera.
--
-- Reconstruida desde el estado real de produccion (version 20260829183340).
-- =============================================================================

begin;

create table if not exists public.recursos (
  id          bigint generated by default as identity primary key,
  sede_id     text not null references public.sedes(id) on update cascade on delete restrict,
  nombre      text not null check (length(btrim(nombre)) between 2 and 120),
  tipo        text,
  descripcion text,
  codigo      text,
  ubicacion   text,
  estado      text not null default 'disponible'
                check (estado in ('disponible','prestado','mantencion','no_disponible')),
  activo      boolean not null default true,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);

comment on table public.recursos is
  'Equipos que se prestan y vuelven. `codigo` esta pensado para un QR pegado al equipo.';

create unique index if not exists recursos_codigo_uidx
  on public.recursos (sede_id, lower(btrim(codigo))) where codigo is not null;
create index if not exists recursos_sede_estado_idx
  on public.recursos (sede_id, estado) where activo;

create table if not exists public.recursos_prestamos (
  id                        bigint generated by default as identity primary key,
  recurso_id                bigint not null references public.recursos(id) on update cascade on delete restrict,
  sede_id                   text not null references public.sedes(id) on update cascade on delete restrict,
  prestado_a                uuid not null references public.perfiles(id) on update cascade on delete restrict,
  entregado_por             uuid default auth.uid()
                              references public.perfiles(id) on update cascade on delete set null,
  recibido_por              uuid references public.perfiles(id) on update cascade on delete set null,
  fecha_entrega             date not null default current_date,
  fecha_devolucion_esperada date not null,
  fecha_devolucion_real     date,
  estado_al_entregar        text,
  estado_al_devolver        text,
  observaciones             text,
  created_at                timestamptz not null default now(),
  updated_at                timestamptz not null default now(),

  constraint plazo_posterior      check (fecha_devolucion_esperada >= fecha_entrega),
  constraint devolucion_posterior check (fecha_devolucion_real is null
                                         or fecha_devolucion_real >= fecha_entrega)
);

-- Un recurso, un prestamo abierto. Lo garantiza la base, no el formulario.
create unique index if not exists prestamos_uno_activo_por_recurso
  on public.recursos_prestamos (recurso_id) where fecha_devolucion_real is null;
create index if not exists prestamos_pendientes_idx
  on public.recursos_prestamos (sede_id, fecha_devolucion_esperada) where fecha_devolucion_real is null;
create index if not exists prestamos_persona_idx
  on public.recursos_prestamos (prestado_a, fecha_entrega desc);
create index if not exists prestamos_recurso_idx
  on public.recursos_prestamos (recurso_id, fecha_entrega desc);

-- -----------------------------------------------------------------------------
-- La sede y la disponibilidad las decide la base, con la fila bloqueada
-- -----------------------------------------------------------------------------
create or replace function public.preparar_prestamo()
returns trigger
language plpgsql
security definer
set search_path = public
as $fn$
declare r public.recursos;
begin
  select * into r from public.recursos where id = new.recurso_id for update;
  if not found then raise exception 'El recurso no existe'; end if;
  if not r.activo then raise exception 'El recurso "%" esta dado de baja', r.nombre; end if;
  if r.estado = 'mantencion' then
    raise exception 'El recurso "%" esta en mantencion', r.nombre;
  end if;
  if r.estado = 'no_disponible' then
    raise exception 'El recurso "%" no esta disponible para prestamo', r.nombre;
  end if;

  new.sede_id := r.sede_id;
  new.fecha_devolucion_real := null;
  new.recibido_por := null;
  return new;
end;
$fn$;

create or replace function public.enforce_prestamo_update()
returns trigger
language plpgsql
security definer
set search_path = public
as $fn$
begin
  if old.fecha_devolucion_real is not null
     and new.fecha_devolucion_real is distinct from old.fecha_devolucion_real then
    raise exception 'El prestamo ya fue devuelto';
  end if;

  if (new.recurso_id, new.prestado_a, new.fecha_entrega, new.sede_id)
       is distinct from (old.recurso_id, old.prestado_a, old.fecha_entrega, old.sede_id) then
    raise exception 'No se puede cambiar a quien ni que se presto';
  end if;

  -- Registrar la devolucion deja constancia de quien la recibio.
  if new.fecha_devolucion_real is not null and old.fecha_devolucion_real is null then
    new.recibido_por := auth.uid();
  end if;

  return new;
end;
$fn$;

create or replace function public.sincronizar_estado_recurso()
returns trigger
language plpgsql
security definer
set search_path = public
as $fn$
declare
  objetivo bigint := coalesce(new.recurso_id, old.recurso_id);
  hay_activo boolean;
begin
  select exists(
    select 1 from public.recursos_prestamos
    where recurso_id = objetivo and fecha_devolucion_real is null
  ) into hay_activo;

  -- `mantencion` y `no_disponible` los pone una persona a proposito: no se
  -- pisan por un prestamo.
  update public.recursos
  set estado = case when hay_activo then 'prestado' else 'disponible' end,
      updated_at = now()
  where id = objetivo and estado in ('disponible','prestado');

  return null;
end;
$fn$;

drop trigger if exists recursos_set_updated_at on public.recursos;
create trigger recursos_set_updated_at
  before update on public.recursos
  for each row execute function public.set_updated_at();

drop trigger if exists recursos_audit on public.recursos;
create trigger recursos_audit
  after insert or delete or update on public.recursos
  for each row execute function public.audit_row_change();

drop trigger if exists prestamos_preparar on public.recursos_prestamos;
create trigger prestamos_preparar
  before insert on public.recursos_prestamos
  for each row execute function public.preparar_prestamo();

drop trigger if exists prestamos_enforce_update on public.recursos_prestamos;
create trigger prestamos_enforce_update
  before update on public.recursos_prestamos
  for each row execute function public.enforce_prestamo_update();

drop trigger if exists prestamos_set_updated_at on public.recursos_prestamos;
create trigger prestamos_set_updated_at
  before update on public.recursos_prestamos
  for each row execute function public.set_updated_at();

drop trigger if exists prestamos_sincronizar on public.recursos_prestamos;
create trigger prestamos_sincronizar
  after insert or delete or update on public.recursos_prestamos
  for each row execute function public.sincronizar_estado_recurso();

-- -----------------------------------------------------------------------------
-- Vista: lo que esta afuera y desde cuando
-- -----------------------------------------------------------------------------
create or replace view public.prestamos_vista
with (security_invoker = true) as
select
  p.id, p.recurso_id, r.nombre as recurso, r.codigo, r.tipo,
  p.sede_id, p.prestado_a, q.nombre as prestado_a_nombre,
  p.fecha_entrega, p.fecha_devolucion_esperada, p.fecha_devolucion_real,
  p.estado_al_entregar, p.estado_al_devolver, p.observaciones,
  p.fecha_devolucion_esperada - public.hoy_santiago() as dias_restantes,
  case
    when p.fecha_devolucion_real is not null                then 'devuelto'
    when p.fecha_devolucion_esperada < public.hoy_santiago() then 'atrasado'
    else 'prestado'
  end as situacion,
  p.created_at
from public.recursos_prestamos p
join public.recursos r on r.id = p.recurso_id
join public.perfiles q on q.id = p.prestado_a;

-- -----------------------------------------------------------------------------
-- RLS — todos ven quien tiene que; presta y recibe quien administra la bodega
-- -----------------------------------------------------------------------------
alter table public.recursos           enable row level security;
alter table public.recursos_prestamos enable row level security;

drop policy if exists "recursos_select" on public.recursos;
create policy "recursos_select" on public.recursos
  for select to authenticated
  using (public.can_access_sede(sede_id));

drop policy if exists "recursos_manage" on public.recursos;
create policy "recursos_manage" on public.recursos
  for all to authenticated
  using (public.can_access_sede(sede_id) and public.gestiona_bodega())
  with check (public.can_access_sede(sede_id) and public.gestiona_bodega());

-- Que un notebook lo tenga alguien no es secreto: si esta afuera, el resto
-- necesita saber a quien pedirselo.
drop policy if exists "prestamos_select" on public.recursos_prestamos;
create policy "prestamos_select" on public.recursos_prestamos
  for select to authenticated
  using (public.can_access_sede(sede_id));

drop policy if exists "prestamos_insert" on public.recursos_prestamos;
create policy "prestamos_insert" on public.recursos_prestamos
  for insert to authenticated
  with check (public.gestiona_bodega() and exists (
    select 1 from public.recursos r
    where r.id = recurso_id and public.can_access_sede(r.sede_id)
  ));

drop policy if exists "prestamos_update" on public.recursos_prestamos;
create policy "prestamos_update" on public.recursos_prestamos
  for update to authenticated
  using (public.can_access_sede(sede_id) and public.gestiona_bodega())
  with check (public.can_access_sede(sede_id) and public.gestiona_bodega());

grant select, insert, update, delete on public.recursos           to authenticated;
grant select, insert, update         on public.recursos_prestamos to authenticated;
grant select                         on public.prestamos_vista    to authenticated;

revoke all on public.recursos           from anon;
revoke all on public.recursos_prestamos from anon;
revoke all on public.prestamos_vista    from anon;
revoke truncate, trigger, references on public.recursos, public.recursos_prestamos
  from anon, authenticated;

revoke all on function public.preparar_prestamo()          from public, anon, authenticated;
revoke all on function public.enforce_prestamo_update()    from public, anon, authenticated;
revoke all on function public.sincronizar_estado_recurso() from public, anon, authenticated;

commit;
