-- =============================================================================
-- Fase 5 — Mantenciones correctivas
--
-- Lo que se rompe se reporta desde el celular, con foto, en el momento en que
-- se ve. Antes eso vivia en un WhatsApp que se perdia entre mensajes.
--
-- Dos reglas sostienen el modulo:
--   · El reporte original no se reescribe. Si estaba mal, se cancela y se
--     reporta de nuevo: cambiar el texto dejaria el historial mintiendo.
--   · Los estados existen todos pero no se obliga a recorrerlos. En una escuela
--     chica `reportada -> resuelta` es un camino legitimo; el resto esta para
--     cuando hay que cotizar o programar a un tercero.
--
-- Reconstruida desde el estado real de produccion (version 20260829181235).
-- =============================================================================

begin;

-- -----------------------------------------------------------------------------
-- 1. Quien gestiona mantencion
-- -----------------------------------------------------------------------------
create or replace function public.gestiona_mantencion()
returns boolean
language sql
stable
security definer
set search_path = public
as $fn$
  select coalesce(public.has_role(array['director','sostenedor','mantencion']), false);
$fn$;

-- -----------------------------------------------------------------------------
-- 2. Categorias — configurables, no escritas en el codigo
-- -----------------------------------------------------------------------------
create table if not exists public.mantencion_categorias (
  id         bigint generated by default as identity primary key,
  nombre     text not null,
  activo     boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create unique index if not exists mantencion_categorias_nombre_uidx
  on public.mantencion_categorias (lower(btrim(nombre)));

insert into public.mantencion_categorias (nombre)
values ('Gasfiteria'), ('Electricidad'), ('Infraestructura'), ('Mobiliario'),
       ('Tecnologia'), ('Areas verdes'), ('Seguridad'), ('Calefaccion'),
       ('Aseo'), ('Equipamiento'), ('Otros')
on conflict do nothing;

-- -----------------------------------------------------------------------------
-- 3. Incidencias
-- -----------------------------------------------------------------------------
create table if not exists public.mantenciones (
  id                bigint generated by default as identity primary key,
  sede_id           text not null references public.sedes(id) on update cascade on delete restrict,
  categoria_id      bigint not null references public.mantencion_categorias(id) on update cascade on delete restrict,
  lugar             text not null check (length(btrim(lugar)) between 2 and 120),
  descripcion       text not null check (length(btrim(descripcion)) >= 5),
  prioridad         text not null default 'media'
                      check (prioridad in ('baja','media','alta','urgente')),
  estado            text not null default 'reportada'
                      check (estado in ('reportada','revisando','pendiente','cotizando',
                                        'programada','en_reparacion','resuelta','cerrada','cancelada')),
  reportado_por     uuid not null default auth.uid()
                      references public.perfiles(id) on update cascade on delete restrict,
  asignado_a        uuid references public.perfiles(id) on update cascade on delete set null,
  fecha_programada  date,
  proveedor         text,
  costo             numeric(12,2) check (costo >= 0),
  trabajo_realizado text,
  resuelta_por      uuid references public.perfiles(id) on update cascade on delete set null,
  resuelta_en       timestamptz,
  cerrada_en        timestamptz,
  created_at        timestamptz not null default now(),
  updated_at        timestamptz not null default now(),

  -- Una mantencion resuelta tiene fecha de resolucion, y una que no lo esta no
  -- arrastra rastros de una resolucion anterior.
  constraint resolucion_mantencion_coherente check (
    (estado in ('resuelta','cerrada') and resuelta_en is not null)
    or (estado not in ('resuelta','cerrada') and resuelta_en is null and resuelta_por is null)
  )
);

comment on table public.mantenciones is
  'Incidencias de mantencion. Los estados existen todos pero no se obliga a recorrerlos: reportada -> resuelta es un camino valido.';

create index if not exists mantenciones_bandeja_idx
  on public.mantenciones (sede_id, estado, prioridad);
create index if not exists mantenciones_reportante_idx
  on public.mantenciones (reportado_por, created_at desc);
create index if not exists mantenciones_abiertas_idx
  on public.mantenciones (sede_id, created_at desc)
  where estado not in ('cerrada','cancelada');
create index if not exists mantenciones_urgentes_idx
  on public.mantenciones (sede_id)
  where prioridad = 'urgente' and estado not in ('resuelta','cerrada','cancelada');

-- -----------------------------------------------------------------------------
-- 4. Historial — quien hizo que y cuando
-- -----------------------------------------------------------------------------
create table if not exists public.mantenciones_historial (
  id              bigint generated by default as identity primary key,
  mantencion_id   bigint not null references public.mantenciones(id) on delete cascade,
  estado_anterior text,
  estado_nuevo    text not null,
  actor_id        uuid references public.perfiles(id) on update cascade on delete set null,
  comentario      text,
  created_at      timestamptz not null default now()
);

create index if not exists mantenciones_historial_idx
  on public.mantenciones_historial (mantencion_id, created_at);

-- -----------------------------------------------------------------------------
-- 5. Adjuntos: la foto de lo que se rompio, y la de como quedo
-- -----------------------------------------------------------------------------
alter table public.adjuntos_solicitudes
  drop constraint if exists adjuntos_solicitudes_origen_check;
alter table public.adjuntos_solicitudes
  add constraint adjuntos_solicitudes_origen_check
  check (origen in ('permiso','material','mantencion'));

alter table public.adjuntos_solicitudes
  add column if not exists momento text;
alter table public.adjuntos_solicitudes
  drop constraint if exists adjuntos_solicitudes_momento_check;
alter table public.adjuntos_solicitudes
  add constraint adjuntos_solicitudes_momento_check
  check (momento in ('antes','despues'));

-- Quien repara tiene que poder ver la foto de lo que va a reparar, aunque no
-- la haya subido el. Sin esto la foto solo la veia direccion.
drop policy if exists "adjuntos_select" on public.adjuntos_solicitudes;
create policy "adjuntos_select" on public.adjuntos_solicitudes
  for select to authenticated
  using (
    subido_por = auth.uid()
    or (public.can_access_sede(sede_id) and (
          public.has_role(array['director','sostenedor','secretaria'])
          or (origen = 'mantencion' and public.gestiona_mantencion())
       ))
  );

-- -----------------------------------------------------------------------------
-- 6. La base pone el reportante y el estado inicial, no el cliente
-- -----------------------------------------------------------------------------
create or replace function public.preparar_mantencion()
returns trigger
language plpgsql
security definer
set search_path = public
as $fn$
begin
  new.reportado_por := auth.uid();
  new.estado        := 'reportada';
  new.resuelta_por  := null;
  new.resuelta_en   := null;
  new.cerrada_en    := null;
  new.costo         := null;
  return new;
end;
$fn$;

create or replace function public.enforce_mantencion_transicion()
returns trigger
language plpgsql
security definer
set search_path = public
as $fn$
declare
  es_reportante boolean := old.reportado_por = auth.uid();
  gestiona      boolean := public.gestiona_mantencion();
begin
  if old.estado in ('cerrada','cancelada') then
    raise exception 'La mantencion ya esta cerrada y no admite cambios';
  end if;

  if new.estado is distinct from old.estado then
    if new.estado = 'cancelada' then
      if not (es_reportante or gestiona) then
        raise exception 'Solo quien reporto o quien gestiona mantencion puede cancelar';
      end if;

    elsif new.estado = 'cerrada' then
      if not gestiona then
        raise exception 'Solo quien gestiona mantencion puede cerrar';
      end if;
      if old.estado <> 'resuelta' then
        raise exception 'Antes de cerrar hay que marcarla como resuelta';
      end if;
      new.cerrada_en := now();

    elsif new.estado = 'resuelta' then
      if not gestiona then
        raise exception 'Solo quien gestiona mantencion puede marcarla resuelta';
      end if;
      if coalesce(btrim(new.trabajo_realizado), '') = '' then
        raise exception 'Para resolver hay que describir que se hizo';
      end if;
      new.resuelta_por := auth.uid();
      new.resuelta_en  := now();

    else
      if not gestiona then
        raise exception 'Solo quien gestiona mantencion puede cambiar el estado';
      end if;
    end if;
  end if;

  -- Lo que se reporto no se reescribe: si estaba mal, se cancela y se reporta
  -- de nuevo. Cambiar el texto dejaria el historial mintiendo.
  if (new.lugar, new.descripcion, new.reportado_por, new.sede_id)
       is distinct from (old.lugar, old.descripcion, old.reportado_por, old.sede_id) then
    raise exception 'El reporte original no se modifica';
  end if;

  -- Prioridad, categoria, asignacion, fecha y costo solo los toca la gestion.
  if (new.prioridad, new.categoria_id, new.asignado_a, new.fecha_programada,
      new.proveedor, new.costo) is distinct from
     (old.prioridad, old.categoria_id, old.asignado_a, old.fecha_programada,
      old.proveedor, old.costo)
     and not gestiona then
    raise exception 'Solo quien gestiona mantencion puede cambiar estos datos';
  end if;

  return new;
end;
$fn$;

create or replace function public.registrar_historial_mantencion()
returns trigger
language plpgsql
security definer
set search_path = public
as $fn$
begin
  if tg_op = 'INSERT' then
    insert into public.mantenciones_historial (mantencion_id, estado_anterior, estado_nuevo, actor_id, comentario)
    values (new.id, null, new.estado, auth.uid(), 'Problema reportado');
  elsif new.estado is distinct from old.estado then
    insert into public.mantenciones_historial (mantencion_id, estado_anterior, estado_nuevo, actor_id, comentario)
    values (new.id, old.estado, new.estado, auth.uid(),
            case when new.estado = 'resuelta' then new.trabajo_realizado else null end);
  end if;
  return new;
end;
$fn$;

-- Al reportar avisa a quien puede resolver; al resolver avisa a quien reporto.
create or replace function public.notificar_mantencion()
returns trigger
language plpgsql
security definer
set search_path = public
as $fn$
begin
  if tg_op = 'INSERT' then
    insert into public.notificaciones (destinatario_id, tipo, titulo, cuerpo, enlace)
    select p.id, 'mantencion_reportada',
           case when new.prioridad = 'urgente'
                then 'Incidencia URGENTE en ' || new.lugar
                else 'Nueva incidencia en ' || new.lugar end,
           new.descripcion, '/mantenciones/' || new.id
    from public.perfiles p
    where p.activo = true
      and p.rol in ('director','sostenedor','mantencion')
      and p.id <> new.reportado_por;

  elsif new.estado is distinct from old.estado and new.estado in ('resuelta','cancelada') then
    perform public.crear_notificacion(
      new.reportado_por, 'mantencion_resuelta',
      case when new.estado = 'resuelta' then 'Se resolvio lo que reportaste'
           else 'Se cancelo lo que reportaste' end,
      new.lugar || ' — ' || new.descripcion, '/mantenciones/' || new.id);
  end if;
  return new;
end;
$fn$;

drop trigger if exists mantencion_categorias_set_updated_at on public.mantencion_categorias;
create trigger mantencion_categorias_set_updated_at
  before update on public.mantencion_categorias
  for each row execute function public.set_updated_at();

drop trigger if exists mantenciones_preparar on public.mantenciones;
create trigger mantenciones_preparar
  before insert on public.mantenciones
  for each row execute function public.preparar_mantencion();

drop trigger if exists mantenciones_transicion on public.mantenciones;
create trigger mantenciones_transicion
  before update on public.mantenciones
  for each row execute function public.enforce_mantencion_transicion();

drop trigger if exists mantenciones_set_updated_at on public.mantenciones;
create trigger mantenciones_set_updated_at
  before update on public.mantenciones
  for each row execute function public.set_updated_at();

drop trigger if exists mantenciones_historial_trg on public.mantenciones;
create trigger mantenciones_historial_trg
  after insert or update on public.mantenciones
  for each row execute function public.registrar_historial_mantencion();

drop trigger if exists mantenciones_notificar on public.mantenciones;
create trigger mantenciones_notificar
  after insert or update on public.mantenciones
  for each row execute function public.notificar_mantencion();

drop trigger if exists mantenciones_audit on public.mantenciones;
create trigger mantenciones_audit
  after insert or delete or update on public.mantenciones
  for each row execute function public.audit_row_change();

-- -----------------------------------------------------------------------------
-- 7. RLS
--
-- Reportar lo puede hacer cualquiera que trabaje en la sede: el problema lo ve
-- quien esta parado ahi, no quien lo va a arreglar.
-- -----------------------------------------------------------------------------
alter table public.mantencion_categorias   enable row level security;
alter table public.mantenciones            enable row level security;
alter table public.mantenciones_historial  enable row level security;

drop policy if exists "mant_categorias_select" on public.mantencion_categorias;
create policy "mant_categorias_select" on public.mantencion_categorias
  for select to authenticated
  using (public.is_active_user());

drop policy if exists "mant_categorias_manage" on public.mantencion_categorias;
create policy "mant_categorias_manage" on public.mantencion_categorias
  for all to authenticated
  using (public.gestiona_mantencion())
  with check (public.gestiona_mantencion());

drop policy if exists "mantenciones_select_sede" on public.mantenciones;
create policy "mantenciones_select_sede" on public.mantenciones
  for select to authenticated
  using (public.can_access_sede(sede_id));

drop policy if exists "mantenciones_insert_personal" on public.mantenciones;
create policy "mantenciones_insert_personal" on public.mantenciones
  for insert to authenticated
  with check (public.can_access_sede(sede_id) and reportado_por = auth.uid());

drop policy if exists "mantenciones_update" on public.mantenciones;
create policy "mantenciones_update" on public.mantenciones
  for update to authenticated
  using (public.can_access_sede(sede_id)
         and (reportado_por = auth.uid() or public.gestiona_mantencion()))
  with check (public.can_access_sede(sede_id)
         and (reportado_por = auth.uid() or public.gestiona_mantencion()));

-- El historial lo escribe el trigger, nadie mas: no hay politica de insert.
drop policy if exists "mantenciones_historial_select" on public.mantenciones_historial;
create policy "mantenciones_historial_select" on public.mantenciones_historial
  for select to authenticated
  using (exists (
    select 1 from public.mantenciones m
    where m.id = mantencion_id and public.can_access_sede(m.sede_id)
  ));

grant select                 on public.mantencion_categorias  to authenticated;
grant insert, update, delete on public.mantencion_categorias  to authenticated;
grant select, insert, update on public.mantenciones           to authenticated;
grant select                 on public.mantenciones_historial to authenticated;

revoke all on public.mantencion_categorias  from anon;
revoke all on public.mantenciones           from anon;
revoke all on public.mantenciones_historial from anon;
revoke truncate, trigger, references on public.mantencion_categorias, public.mantenciones,
  public.mantenciones_historial from anon, authenticated;

-- Las de trigger no las llama nadie desde afuera.
revoke all on function public.preparar_mantencion()            from public, anon, authenticated;
revoke all on function public.enforce_mantencion_transicion()  from public, anon, authenticated;
revoke all on function public.registrar_historial_mantencion() from public, anon, authenticated;
revoke all on function public.notificar_mantencion()           from public, anon, authenticated;
revoke all on function public.gestiona_mantencion()            from anon;

commit;
