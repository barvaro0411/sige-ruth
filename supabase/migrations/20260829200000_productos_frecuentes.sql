-- =============================================================================
-- Fase 4 — Productos frecuentes
--
-- Para que la persona de aseo abra la app y vea de entrada el cloro, el confort
-- y las bolsas, en vez de buscar en una lista con todo el inventario.
--
-- El alcance es por rol o por persona, nunca los dos a la vez: «esto lo ve todo
-- el que hace aseo» o «esto lo ve María». Un producto puede estar en ambas
-- listas, por filas distintas.
-- =============================================================================

begin;

create table if not exists public.productos_frecuentes (
  id         bigint generated by default as identity primary key,
  item_id    bigint not null references public.inventario_items(id) on update cascade on delete cascade,
  rol        text,
  perfil_id  uuid references public.perfiles(id) on update cascade on delete cascade,
  orden      smallint not null default 0,
  created_at timestamptz not null default now(),

  -- Exactamente uno de los dos: o es del rol, o es de la persona.
  constraint alcance_definido check (num_nonnulls(rol, perfil_id) = 1),
  constraint rol_valido check (
    rol is null or rol in ('director','sostenedor','secretaria','docente',
                           'fonoaudiologo','jefe_utp','aseo','bodega','mantencion')
  )
);

create unique index if not exists productos_frecuentes_rol_uidx
  on public.productos_frecuentes (rol, item_id) where rol is not null;
create unique index if not exists productos_frecuentes_perfil_uidx
  on public.productos_frecuentes (perfil_id, item_id) where perfil_id is not null;

comment on table public.productos_frecuentes is
  'Lo que cada tipo de trabajador pide habitualmente, para que aparezca primero.';

-- Lo que a mí me toca ver: por mi rol o por mi nombre.
create or replace view public.mis_productos_frecuentes_vista
with (security_invoker = true) as
select
  f.id as frecuente_id,
  f.orden,
  f.rol,
  f.perfil_id,
  i.*
from public.productos_frecuentes f
join public.inventario_estado_vista i on i.id = f.item_id
where f.rol = public.current_profile_role()
   or f.perfil_id = auth.uid();

comment on view public.mis_productos_frecuentes_vista is
  'Productos frecuentes del usuario actual, con su estado de stock. security_invoker: la RLS de inventario_items decide qué sedes ve.';

alter table public.productos_frecuentes enable row level security;

drop policy if exists "frecuentes_select" on public.productos_frecuentes;
create policy "frecuentes_select" on public.productos_frecuentes
  for select to authenticated
  using (exists (
    select 1 from public.inventario_items i
    where i.id = item_id and public.can_access_sede(i.sede_id)
  ));

-- Los configura quien administra la bodega, que es quien sabe qué se pide.
drop policy if exists "frecuentes_manage" on public.productos_frecuentes;
create policy "frecuentes_manage" on public.productos_frecuentes
  for all to authenticated
  using (public.gestiona_bodega() and exists (
    select 1 from public.inventario_items i
    where i.id = item_id and public.can_access_sede(i.sede_id)
  ))
  with check (public.gestiona_bodega() and exists (
    select 1 from public.inventario_items i
    where i.id = item_id and public.can_access_sede(i.sede_id)
  ));

grant select on public.productos_frecuentes                 to authenticated;
grant insert, update, delete on public.productos_frecuentes to authenticated;
grant select on public.mis_productos_frecuentes_vista       to authenticated;
revoke all on public.productos_frecuentes           from anon;
revoke all on public.mis_productos_frecuentes_vista from anon;
revoke truncate, trigger, references on public.productos_frecuentes from anon, authenticated;

commit;
