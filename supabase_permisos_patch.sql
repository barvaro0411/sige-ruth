-- =============================================================================
-- Modulo de permisos / dias administrativos  [APLICADO el 2026-08-28]
--
-- Sigue las convenciones del resto del esquema: identity bigint, sede_id
-- obligatorio, timestamps con set_updated_at, auditoria automatica y RLS
-- con los helpers has_role() / can_access_sede().
--
-- OJO: el event trigger `rls_auto_enable` activa RLS solo al crear la tabla.
-- Hasta que existan las politicas, la tabla es invisible para todos.
-- =============================================================================

-- -----------------------------------------------------------------------------
-- 1. Cupo anual por persona. Se separa de la solicitud para poder ajustarlo
--    por contrato: el numero de dias administrativos depende del estatuto o
--    del contrato de cada trabajador, no es un valor universal.
-- -----------------------------------------------------------------------------
create table if not exists public.cupos_permiso (
  perfil_id  uuid    not null references public.perfiles(id) on update cascade on delete cascade,
  anio       int     not null,
  dias_administrativos numeric(4,1) not null default 6 check (dias_administrativos >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  primary key (perfil_id, anio)
);

-- -----------------------------------------------------------------------------
-- 2. Solicitudes.
--    `dias_habiles` se calcula en el trigger y se guarda: si despues cambian
--    los feriados, las solicitudes ya resueltas no deben mutar.
-- -----------------------------------------------------------------------------
create table if not exists public.solicitudes_permiso (
  id            bigint generated by default as identity primary key,
  solicitante_id uuid  not null references public.perfiles(id) on update cascade on delete restrict,
  sede_id       text   not null references public.sedes(id)    on update cascade on delete restrict,
  tipo          text   not null check (tipo in ('administrativo','licencia_medica','sin_goce','capacitacion','otro')),
  fecha_inicio  date   not null,
  fecha_fin     date   not null,
  jornada       text   not null default 'completa' check (jornada in ('completa','manana','tarde')),
  dias_habiles  numeric(4,1) not null default 0,
  motivo        text,
  estado        text   not null default 'pendiente' check (estado in ('pendiente','aprobada','rechazada','cancelada')),
  resuelta_por  uuid   references public.perfiles(id) on update cascade on delete set null,
  resuelta_en   timestamptz,
  comentario_resolucion text,
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now(),
  constraint rango_valido check (fecha_fin >= fecha_inicio),
  constraint resolucion_coherente check (
    (estado = 'pendiente' and resuelta_por is null and resuelta_en is null)
    or (estado <> 'pendiente')
  )
);

create index if not exists solicitudes_permiso_solicitante_idx
  on public.solicitudes_permiso (solicitante_id, fecha_inicio desc);
create index if not exists solicitudes_permiso_pendientes_idx
  on public.solicitudes_permiso (sede_id, estado) where estado = 'pendiente';

-- -----------------------------------------------------------------------------
-- 3. Dias habiles. Cuenta lunes a viernes; media jornada cuenta 0.5.
--    Los feriados legales NO se descuentan: para eso hace falta una tabla
--    `feriados` y volver a llamar a esta funcion desde el trigger.
-- -----------------------------------------------------------------------------
create or replace function public.dias_habiles_permiso(desde date, hasta date, jornada text)
returns numeric
language sql
immutable
as $$
  select case when jornada = 'completa' then habiles else habiles * 0.5 end
  from (
    select count(*)::numeric as habiles
    from generate_series(desde, hasta, interval '1 day') d
    where extract(isodow from d) < 6
  ) t;
$$;

-- -----------------------------------------------------------------------------
-- 4. Transiciones de estado. RLS decide QUIEN puede escribir la fila; esto
--    decide QUE puede escribir. Sin este trigger, el solicitante podria
--    aprobar su propia solicitud con un update directo a la API.
-- -----------------------------------------------------------------------------
create or replace function public.enforce_permiso_transicion()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  es_solicitante boolean := old.solicitante_id = auth.uid();
  es_jefatura    boolean := public.has_role(array['director','jefe_utp']);
begin
  if old.estado <> 'pendiente' and not public.has_role(array['director']) then
    raise exception 'La solicitud ya fue resuelta';
  end if;

  if new.estado <> old.estado then
    -- El solicitante solo puede retirar la suya.
    if es_solicitante and not public.has_role(array['director']) then
      if new.estado <> 'cancelada' then
        raise exception 'No puedes resolver tu propia solicitud';
      end if;
    elsif not es_jefatura then
      raise exception 'Solo la jefatura puede resolver solicitudes';
    end if;

    if new.estado in ('aprobada','rechazada') then
      new.resuelta_por := auth.uid();
      new.resuelta_en  := now();
    end if;
  end if;

  -- Fechas y motivo solo se editan mientras esta pendiente.
  if old.estado = 'pendiente'
     and (new.fecha_inicio, new.fecha_fin, new.jornada) is distinct from (old.fecha_inicio, old.fecha_fin, old.jornada) then
    if not es_solicitante then
      raise exception 'Solo el solicitante puede modificar las fechas';
    end if;
    new.dias_habiles := public.dias_habiles_permiso(new.fecha_inicio, new.fecha_fin, new.jornada);
  end if;

  return new;
end;
$$;

create or replace function public.set_dias_habiles_permiso()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  new.dias_habiles := public.dias_habiles_permiso(new.fecha_inicio, new.fecha_fin, new.jornada);
  return new;
end;
$$;

drop trigger if exists solicitudes_permiso_dias on public.solicitudes_permiso;
create trigger solicitudes_permiso_dias
  before insert on public.solicitudes_permiso
  for each row execute function public.set_dias_habiles_permiso();

drop trigger if exists solicitudes_permiso_transicion on public.solicitudes_permiso;
create trigger solicitudes_permiso_transicion
  before update on public.solicitudes_permiso
  for each row execute function public.enforce_permiso_transicion();

drop trigger if exists solicitudes_permiso_set_updated_at on public.solicitudes_permiso;
create trigger solicitudes_permiso_set_updated_at
  before update on public.solicitudes_permiso
  for each row execute function public.set_updated_at();

drop trigger if exists solicitudes_permiso_audit on public.solicitudes_permiso;
create trigger solicitudes_permiso_audit
  after insert or update or delete on public.solicitudes_permiso
  for each row execute function public.audit_row_change();

drop trigger if exists cupos_permiso_set_updated_at on public.cupos_permiso;
create trigger cupos_permiso_set_updated_at
  before update on public.cupos_permiso
  for each row execute function public.set_updated_at();

-- -----------------------------------------------------------------------------
-- 5. RLS. El principio: cada trabajador ve lo suyo; la jefatura ve lo de su
--    sede. Un docente NO ve los permisos de sus colegas.
-- -----------------------------------------------------------------------------
alter table public.solicitudes_permiso enable row level security;
alter table public.cupos_permiso       enable row level security;

drop policy if exists "permisos_select_propio_o_jefatura" on public.solicitudes_permiso;
create policy "permisos_select_propio_o_jefatura" on public.solicitudes_permiso
  for select to authenticated
  using (
    solicitante_id = auth.uid()
    or (public.can_access_sede(sede_id) and public.has_role(array['director','jefe_utp']))
  );

drop policy if exists "permisos_insert_propio" on public.solicitudes_permiso;
create policy "permisos_insert_propio" on public.solicitudes_permiso
  for insert to authenticated
  with check (
    solicitante_id = auth.uid()
    and public.can_access_sede(sede_id)
    and estado = 'pendiente'
  );

-- El trigger de transicion acota que puede cambiar cada uno.
drop policy if exists "permisos_update_propio_o_jefatura" on public.solicitudes_permiso;
create policy "permisos_update_propio_o_jefatura" on public.solicitudes_permiso
  for update to authenticated
  using (
    solicitante_id = auth.uid()
    or (public.can_access_sede(sede_id) and public.has_role(array['director','jefe_utp']))
  )
  with check (
    solicitante_id = auth.uid()
    or (public.can_access_sede(sede_id) and public.has_role(array['director','jefe_utp']))
  );

drop policy if exists "permisos_delete_director" on public.solicitudes_permiso;
create policy "permisos_delete_director" on public.solicitudes_permiso
  for delete to authenticated
  using (public.can_access_sede(sede_id) and public.has_role(array['director']));

drop policy if exists "cupos_select_propio_o_jefatura" on public.cupos_permiso;
create policy "cupos_select_propio_o_jefatura" on public.cupos_permiso
  for select to authenticated
  using (perfil_id = auth.uid() or public.has_role(array['director','jefe_utp']));

drop policy if exists "cupos_manage_director" on public.cupos_permiso;
create policy "cupos_manage_director" on public.cupos_permiso
  for all to authenticated
  using (public.has_role(array['director']))
  with check (public.has_role(array['director']));

-- -----------------------------------------------------------------------------
-- 6. Saldo. Vista con security_invoker: cada quien ve las filas que RLS le
--    deja ver, sin logica duplicada.
-- -----------------------------------------------------------------------------
drop view if exists public.saldo_permisos_vista;
create view public.saldo_permisos_vista
with (security_invoker = true) as
select
  c.perfil_id,
  c.anio,
  c.dias_administrativos as asignados,
  coalesce(sum(s.dias_habiles) filter (
    where s.estado = 'aprobada' and s.tipo = 'administrativo'
  ), 0) as usados,
  c.dias_administrativos - coalesce(sum(s.dias_habiles) filter (
    where s.estado = 'aprobada' and s.tipo = 'administrativo'
  ), 0) as disponibles
from public.cupos_permiso c
left join public.solicitudes_permiso s
  on s.solicitante_id = c.perfil_id
 and extract(year from s.fecha_inicio) = c.anio
group by c.perfil_id, c.anio, c.dias_administrativos;

-- -----------------------------------------------------------------------------
-- 7. Grants. Sin GRANT no hay acceso aunque la politica lo permita, y hay que
--    revocar a `public`/`anon` explicitamente (ver supabase_hardening_patch.sql).
-- -----------------------------------------------------------------------------
grant select, insert, update on public.solicitudes_permiso to authenticated;
grant select on public.cupos_permiso to authenticated;
grant insert, update, delete on public.cupos_permiso to authenticated;
grant select on public.saldo_permisos_vista to authenticated;
grant usage, select on all sequences in schema public to authenticated;

revoke all on public.solicitudes_permiso from anon;
revoke all on public.cupos_permiso from anon;
revoke all on public.saldo_permisos_vista from anon;
revoke all on function public.enforce_permiso_transicion() from public, anon, authenticated;
revoke all on function public.set_dias_habiles_permiso() from public, anon, authenticated;

-- -----------------------------------------------------------------------------
-- 8. La auditoria guarda la fila completa en valor_nuevo, incluido `motivo`,
--    que en una licencia medica es dato sensible. Hay que sumar la entidad a
--    la lista que fonoaudiologo/jefe_utp no pueden ver.
-- -----------------------------------------------------------------------------
drop policy if exists "auditoria_select_authorized" on public.auditoria;
create policy "auditoria_select_authorized" on public.auditoria
  for select to authenticated
  using (
    public.can_access_sede(sede_id)
    and (
      public.has_role(array['director'])
      or (
        public.has_role(array['fonoaudiologo','jefe_utp'])
        and entidad not in ('perfiles', 'perfiles_sedes', 'solicitudes_permiso', 'cupos_permiso')
      )
    )
  );

