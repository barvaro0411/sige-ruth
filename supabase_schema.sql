create or replace function public.can_access_sede(target_sede text)
returns boolean language sql stable security definer set search_path = public as $$
  select public.is_active_user()
    and (
      public.current_profile_role() = 'director'
      or exists (
        select 1 from public.perfiles_sedes ps
        where ps.perfil_id = auth.uid() and ps.sede_id = target_sede
      )
    );
$$;

create or replace function public.has_role(allowed_roles text[])
returns boolean language sql stable security definer set search_path = public as $$
  select public.current_profile_role() = any(allowed_roles);
$$;

create or replace function public.audit_row_change()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  old_data jsonb;
  new_data jsonb;
  audit_action text;
  audit_sede text;
  audit_id text;
  audit_entity text;
begin
  old_data := case when tg_op in ('UPDATE', 'DELETE') then to_jsonb(old) else null end;
  new_data := case when tg_op in ('INSERT', 'UPDATE') then to_jsonb(new) else null end;
  audit_action := case tg_op
    when 'INSERT' then 'CREAR'
    when 'UPDATE' then 'MODIFICAR'
    when 'DELETE' then 'ELIMINAR'
  end;

  if tg_table_name = 'asistencia'
     and tg_op in ('INSERT', 'UPDATE')
     and coalesce((new_data ->> 'cerrada')::boolean, false)
     and not coalesce((old_data ->> 'cerrada')::boolean, false) then
    audit_action := 'CERRAR';
  end if;

  audit_sede := coalesce(new_data ->> 'sede_id', old_data ->> 'sede_id');
  audit_id := coalesce(new_data ->> 'id', old_data ->> 'id');
  audit_entity := case when tg_table_name = 'estudiantes' then 'estudiante' else tg_table_name end;

  insert into public.auditoria (
    accion, entidad, entidad_id, usuario_id, valor_anterior, valor_nuevo, sede_id
  ) values (
    audit_action, audit_entity, audit_id, auth.uid(), old_data, new_data, audit_sede
  );

  if tg_op = 'DELETE' then return old; end if;
  return new;
end;
$$;

create or replace function public.enforce_student_sede()
returns trigger language plpgsql set search_path = public as $$
declare
  student_sede text;
begin
  select sede_id into student_sede from public.estudiantes where id = new.estudiante_id;
  if student_sede is null or student_sede <> new.sede_id then
    raise exception 'La sede del registro no coincide con la sede del estudiante';
  end if;
  return new;
end;
$$;

create or replace function public.protect_admin_profiles()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if old.id = auth.uid() and new.activo = false then
    raise exception 'No puedes desactivar tu propia cuenta';
  end if;

  if old.rol = 'director'
     and old.activo = true
     and (new.rol <> 'director' or new.activo = false)
     and not exists (
       select 1 from public.perfiles
       where id <> old.id and rol = 'director' and activo = true
     ) then
    raise exception 'Debe existir al menos un director activo';
  end if;

  return new;
end;
$$;

create or replace function public.update_user_profile(
  target_id uuid,
  target_nombre text,
  target_rol text,
  target_sede_ids text[],
  target_activo boolean
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  primary_sede text;
begin
  if public.current_profile_role() <> 'director' then
    raise exception 'Solo el director puede administrar usuarios';
  end if;
  if target_rol not in ('director', 'secretaria', 'docente', 'fonoaudiologo', 'jefe_utp') then
    raise exception 'Rol inválido';
  end if;
  if target_id = auth.uid() and target_rol <> 'director' then
    raise exception 'No puedes cambiar tu propio rol de director';
  end if;
  if target_rol <> 'director' and coalesce(array_length(target_sede_ids, 1), 0) = 0 then
    raise exception 'El usuario debe tener al menos una sede';
  end if;
  if exists (
    select 1 from unnest(coalesce(target_sede_ids, array[]::text[])) requested(id)
    left join public.sedes s on s.id = requested.id and s.activo = true
    where s.id is null
  ) then
    raise exception 'Una de las sedes no es válida';
  end if;

  primary_sede := case when target_rol = 'director' then null else target_sede_ids[1] end;
  update public.perfiles
  set nombre = trim(target_nombre), rol = target_rol, sede_id = primary_sede, activo = target_activo
  where id = target_id;
  if not found then raise exception 'Usuario no encontrado'; end if;

  delete from public.perfiles_sedes where perfil_id = target_id;
  if target_rol <> 'director' then
    insert into public.perfiles_sedes (perfil_id, sede_id)
    select target_id, requested.id
    from (select distinct unnest(target_sede_ids) as id) requested;
  end if;
end;
$$;

grant execute on function public.update_user_profile(uuid, text, text, text[], boolean) to authenticated;

