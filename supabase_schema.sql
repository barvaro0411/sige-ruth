create or replace function public.set_updated_at()
returns trigger language plpgsql set search_path = public as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  requested_role text;
  requested_sede text;
begin
  -- SEGURIDAD: el rol y la sede NUNCA se toman de raw_user_meta_data (el propio
  -- usuario puede escribirla en signUp/updateUser). Todo perfil nace sin
  -- privilegios; la asignacion real ocurre en la Edge Function admin-users o en
  -- public.update_user_profile, ambas restringidas al director.
  requested_role := 'docente';
  requested_sede := null;

  insert into public.perfiles (id, email, nombre, rol, sede_id)
  values (
    new.id,
    coalesce(new.email, new.id::text || '@sin-email.local'),
    coalesce(nullif(trim(new.raw_user_meta_data ->> 'nombre'), ''), split_part(coalesce(new.email, 'Usuario'), '@', 1)),
    requested_role,
    requested_sede
  )
  on conflict (id) do update set email = excluded.email;

  if requested_sede is not null then
    insert into public.perfiles_sedes (perfil_id, sede_id)
    values (new.id, requested_sede)
    on conflict do nothing;
  end if;

  return new;
end;
$$;

